#!/usr/bin/env python3
"""Generate docs/ops.md, the index of every registered operation, from the registry.

The registry is built the way the server builds it (`ops.register_all`); nothing connects to
Flame. `--check` compares the result with the file on disk and exits 1 on any difference.
"""

from __future__ import annotations

import argparse
import dataclasses
import difflib
import sys
from collections import Counter
from pathlib import Path
from typing import get_args

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from flame_mcp import opschema, policy  # noqa: E402
from flame_mcp.ops import register_all  # noqa: E402
from flame_mcp.registry import RegisteredOperation, Registry  # noqa: E402
from flame_mcp.types import Effect, Undo  # noqa: E402

OUTPUT = ROOT / "docs" / "ops.md"
GATE_MARK = "†"
DIFF_PREVIEW_LINES = 40


def _cell(text: str) -> str:
    parts = text.split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("<", "\\<")
    return "`".join(parts).replace("|", "\\|")


def _build_registry() -> Registry:
    registry = Registry()
    register_all(registry)
    return registry


def _gate_denial(op: RegisteredOperation) -> policy.Denial | None:
    default_policy = policy.Policy.from_env({})
    return policy.deny_operation(dataclasses.replace(op, effect="destructive"), default_policy)


def render(registry: Registry) -> str:
    ops = sorted(registry.list_ops(), key=lambda op: op.name)
    categories = registry.categories()
    names = registry.list_categories()
    counts = Counter(op.category for op in ops)

    lines = [
        "# Operation index",
        "",
        "This file is generated by `scripts/build_ops_index.py`. Do not edit it by hand.",
        "",
        f"{len(ops)} operations in {len(names)} categories.",
        "",
        "## Legend",
        "",
        "**effect**",
        "",
    ]
    lines += [f"- `{effect}`: {policy.effect_label(effect)}" for effect in get_args(Effect)]
    lines += ["", "**undo**", ""]
    lines += [f"- `{undo}`: {policy.undo_label(undo)}" for undo in get_args(Undo)]

    gates = [(op, _gate_denial(op)) for op in ops]
    gated = [(op, denial) for op, denial in gates if denial is not None]
    if gated:
        lines += [
            "",
            f"{GATE_MARK} Gated by the default policy; see [Gated operations](#gated-operations).",
        ]

    lines += ["", "## Categories", "", "| category | operations |", "| --- | ---: |"]
    lines += [f"| [{name}](#{name}) | {counts[name]} |" for name in names]
    lines += ["", "## Operations"]

    gate_names = {op.name for op, _ in gated}
    for name in names:
        lines += ["", f"### {name}", ""]
        description = " ".join(categories[name].description.split())
        if description:
            lines += [f"> {description}", ""]
        lines += ["| op | effect | undo | summary |", "| --- | --- | --- | --- |"]
        for op in (op for op in ops if op.category == name):
            mark = f" {GATE_MARK}" if op.name in gate_names else ""
            summary = _cell(opschema.first_sentence(op.description, limit=None))
            lines.append(f"| `{op.name}`{mark} | {op.effect} | {op.undo} | {summary} |")

    if gated:
        lines += ["", "## Gated operations", ""]
        for op, denial in gated:
            detail = f"{denial.message}. {denial.hint}" if denial.hint else denial.message
            lines.append(
                f"- `{op.name}` is registered with effect `{op.effect}`. Under the default "
                f"policy it is not listed and every call is denied, whatever effect the call "
                f"declares: {detail}"
            )
    return "\n".join(lines) + "\n"


def _check(expected: str) -> int:
    if not OUTPUT.exists():
        print(f"{OUTPUT} does not exist; run scripts/build_ops_index.py", file=sys.stderr)
        return 1
    actual = OUTPUT.read_text(encoding="utf-8")
    if actual == expected:
        return 0
    diff = list(
        difflib.unified_diff(
            actual.splitlines(),
            expected.splitlines(),
            fromfile="docs/ops.md (on disk)",
            tofile="docs/ops.md (generated)",
            lineterm="",
        )
    )
    changed = sum(1 for line in diff if line[:1] in "+-" and line[:3] not in ("+++", "---"))
    print(f"docs/ops.md is out of date: {changed} changed line(s)", file=sys.stderr)
    print("\n".join(diff[:DIFF_PREVIEW_LINES]), file=sys.stderr)
    if len(diff) > DIFF_PREVIEW_LINES:
        print(f"... {len(diff) - DIFF_PREVIEW_LINES} more diff line(s)", file=sys.stderr)
    print("run: .venv/bin/python scripts/build_ops_index.py", file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/ops.md is stale")
    args = parser.parse_args()
    expected = render(_build_registry())
    if args.check:
        return _check(expected)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
