#!/usr/bin/env python3
"""Generate docs/testing.md, the guide to the test suites, from the e2e runner and the clients.

The names and the per-test settings come from `scripts/run_e2e.sh` (`--list` and
`--print-config`); the "what it checks" text is the `Checks:` paragraph of each client's module
docstring. Nothing connects to Flame. `--check` compares the result with the file on disk and
exits 1 on any difference.
"""

from __future__ import annotations

import argparse
import ast
import difflib
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"
RUN_E2E = SCRIPTS / "run_e2e.sh"
OUTPUT = ROOT / "docs" / "testing.md"
DIFF_PREVIEW_LINES = 40
CHECKS_LABEL = "Checks:"
W3_SETUP_ENV = "FLAME_MCP_W3_SETUP"
DEDICATED_RESULTS_RE = re.compile(r'^e2e_init "\$P(\d)_DIR"', re.MULTILINE)

PROSE_HEAD = """\
# Testing

This file is generated by `scripts/build_testing_doc.py`. Do not edit it by hand.

The project has two kinds of tests. The unit tests run anywhere and need no Flame. The real-Flame
regression tests start Flame and check what the operations do to a real project.

## Unit tests

The unit tests are in `tests/`. They use a fake Flame, so they need no Flame.

Some unit tests start a bridge on a Unix socket. A socket path must be short, and pytest's
temporary folder on macOS is too long, so these tests make a folder under
`~/Library/Application Support/flame-mcp/scratch/` and remove it when they finish. The parent
folders stay, empty.

```bash
.venv/bin/pip install -e '.[dev]'
.venv/bin/python -m pytest
```

The static checks use the same environment:

```bash
.venv/bin/ruff check
.venv/bin/ruff format --check
.venv/bin/mypy
```

Two files are generated, `docs/ops.md` and this file. A unit test fails when either one is out
of date. Regenerate them with `scripts/build_ops_index.py` and `scripts/build_testing_doc.py`.

Some unit tests (`tests/test_*_e2e_inprocess.py`) run the real-Flame client scripts against the
fake Flame. They catch a broken client without Flame. They do not replace a real run.

## Real-Flame regression tests

A real-Flame test starts Flame, runs the real MCP server against it through the real bridge,
runs operations, and reads the results back from Flame by a path that does not use the operation
under test. Each test is a client script, `scripts/<name>_e2e.py`. The list is in
[the table below](#the-regression-tests).

These tests write to the project. Follow these rules:

* They run only in a Flame project named `flame_mcp_probe`, or the name in
  `FLAME_MCP_E2E_PROJECT` if you set it. That name must be `flame_mcp_probe` or start with
  `flame_mcp_probe_`, for example `flame_mcp_probe_2026`; any other value stops the script. Each
  client reads the project name from the bridge before it creates anything. In any other project
  it sends nothing to Flame and exits with code 2.
* `pytest` does not run them. They are in `scripts/`, and `pytest` collects only `tests/`.
* They use the development copy of the bridge, not the one you installed. Nothing under
  `/opt/Autodesk` is changed.
* A test makes its test sequences with the bit depth of its media, so that what it expects does
  not depend on the default bit depth of the project.
* The objects a test creates get a name made of a fixed prefix and a time stamp. Most clients
  delete what they made. Some leave objects behind, for example Batch groups. A clean-up script
  removes them. See [Clean up](#clean-up).

See [Safety in real-Flame tests](safety.md#safety-in-real-flame-tests) for the full rules.

### Before you start

* macOS with Flame 2025.2.4 installed at `/opt/Autodesk/flame_2025.2.4`. The scripts start this
  Flame application. To run on another installed version, set `FLAME_MCP_E2E_FLAME_VERSION`, for
  example `2026.2.3`. The scripts then start `/opt/Autodesk/flame_2026.2.3` and read that
  version's logs.
* A Flame project named `flame_mcp_probe`. The runner starts Flame in it. To use another name,
  set `FLAME_MCP_E2E_PROJECT` to a name that starts with `flame_mcp_probe_`. When you run another
  version, use a project made in that version and give it its own name: a newer Flame can ask to
  convert a project made in an older version, and a project that has been converted is no longer
  the one the older version made.
* The development environment from [Unit tests](#unit-tests). The runner uses
  `.venv/bin/python` in the repository.
* Flame must not be running. A runner stops if it finds a running Flame of any version.
* The test media, described next.

### Prepare the media

The tests read their media from `~/Library/Application Support/flame-mcp/probe_project/media/`.

* `clip1.mov`, `clip2.mov` and `clip3.mov` (red, green and blue), directly in that folder. The tests
  expect clips of 24 frames, 1920x1080, at 23.976 fps. Make them with `scripts/make_clip_media.sh`.
* `p2/p2_len48.mov`, `p2/p2_len72.mov` and `p2/p2_len12.mov`, with 48, 72 and 12 frames. Make
  them with `scripts/make_p2_media.sh`.
* `p2/p2_src_tc1h.mov`, `p2/p2_rep_tc1h.mov`, `p2/p2_rep_tc1h_plus10.mov` and
  `p2/p2_rep_tc2h.mov`, 48 frames each, with different start timecodes. Make them with
  `scripts/make_p2_tc_media.sh`.

All three scripts need `ffmpeg` and `ffprobe` on your `PATH`. Each takes an output folder as an
optional argument. `make_clip_media.sh` writes to the media folder itself when you give none, and
the other two write to the `p2` folder named above. `make_clip_media.sh` stops without writing
anything when a clip is already there; add `--force` to replace it.

```bash
scripts/make_clip_media.sh
scripts/make_p2_media.sh
scripts/make_p2_tc_media.sh
```

### Run the tests

Run one test. The optional second argument is the number of seconds to wait for Flame to exit
by itself after the client returns. The default is 600.

```bash
scripts/run_e2e.sh p2_2a_journal
scripts/run_e2e.sh p2_2a_journal 900
```

Run every test, one after another, and clean up at the end. Give names to run only those.

```bash
scripts/regress.sh
scripts/regress.sh p1_mcp p2_1_attr
```

Other forms of `scripts/run_e2e.sh`:

```bash
scripts/run_e2e.sh --list                  # the names, in the order regress.sh runs them
scripts/run_e2e.sh --print-config <name>   # what a name resolves to; starts nothing
```

For each run, the runner deploys the development bridge, starts Flame, waits for the bridge
socket, runs the client, and waits for Flame to exit. If Flame crashes or does not exit in time,
the runner takes a sample and stops Flame. Then it prints the exit route, the Flame log lines
about the bridge, the end of the bridge log, and the latest result file.

Two settings change a run:

* `E2E_EXTRA_ARGS` adds arguments to the client for the tests whose notes say so. For example,
  `E2E_EXTRA_ARGS='--reads 300 --writes 100 --parallel-writes 50' scripts/run_e2e.sh p2_4_stress`.
* `FLAME_MCP_W3_SETUP` is the path of a setup file of a segment that has a Timewarp, saved from
  the Flame interface. `w3_timewarp` needs it. While it is unset, or the file does not exist,
  the runner prints `SKIP`, does not start Flame, and exits with 0.

### Where the results go

Each client writes a result file named `<name>_e2e_<timestamp>.json`. The files are in
`~/Library/Application Support/flame-mcp/p1/`, `.../p2/` or `.../p3/`. The table names the folder
of each test. The launch log, crash samples and each run's own journal and files are in the same
folder.

`scripts/regress.sh` writes to a new folder, `p3/regress_<timestamp>/`, and records its path in
`p3/regress_latest.txt`:

* `<name>_<n>.log` is the full output of one run.
* `summary.txt` has one line per run: the start time, the exit code, the number of abnormal
  terminations, and the exit route. A run that the runner skipped on its own reads
  `SKIPPED: <reason>`. If Flame is already running, the loop ends at that point.
* `clean.log` is the output of the clean-up.

### Clean up

`scripts/regress.sh` runs the clean-up when it finishes. After a single run, run it yourself.
The first command prints what the script would delete, keep and create. The second does it. The
number 900 is how many seconds to wait for Flame to exit.

```bash
scripts/run_flame_with_bridge.sh scripts/p2_4_clean_probe_project.py 900 -- --mode dry-run
scripts/run_flame_with_bridge.sh scripts/p2_4_clean_probe_project.py 900 -- --mode apply
```

The script deletes only libraries, Batch groups and reel groups whose names have the form a test
uses. It does not touch projects, shared libraries or files on disk. Results, journals and
rendered files stay in the results folders until you delete them.

### The regression tests

The first part of each name (`p1_`, `p2_`, `p3_`, `fix2_`, `w3_` and so on) is a serial number in
the order the tests were written. It has no other meaning.

"""

TABLE_HEAD = """\
| test | results in | what it checks | notes |
| --- | --- | --- | --- |
"""


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _run_e2e(*args: str) -> str:
    env = {key: value for key, value in os.environ.items() if key != W3_SETUP_ENV}
    result = subprocess.run(
        ["bash", str(RUN_E2E), *args],
        capture_output=True,
        text=True,
        check=True,
        env=env,
        cwd=ROOT,
    )
    return result.stdout


def e2e_names() -> list[str]:
    return _run_e2e("--list").split()


def e2e_config(name: str) -> dict[str, str]:
    config: dict[str, str] = {}
    for line in _run_e2e("--print-config", name).splitlines():
        key, _, value = line.partition("=")
        config[key] = value
    return config


def extract_checks(source: str, label: str) -> str:
    """Returns the text of the `Checks:` paragraph in the module docstring of `source`.

    The paragraph runs from a line that starts with `Checks:` to the next blank line. Raises
    ValueError, naming `label`, when there is no docstring or not exactly one such paragraph.
    """
    docstring = ast.get_docstring(ast.parse(source))
    if docstring is None:
        raise ValueError(f"{label}: no module docstring")
    paragraphs = [p for p in re.split(r"\n\s*\n", docstring) if p.startswith(CHECKS_LABEL)]
    if len(paragraphs) != 1:
        raise ValueError(
            f"{label}: expected one '{CHECKS_LABEL}' paragraph, found {len(paragraphs)}"
        )
    return " ".join(paragraphs[0][len(CHECKS_LABEL) :].split())


def client_checks(name: str) -> str:
    path = SCRIPTS / f"{name}_e2e.py"
    return extract_checks(path.read_text(encoding="utf-8"), path.name)


def _results_folder(name: str, config: dict[str, str]) -> str:
    if config["runner"] == "dedicated":
        orchestrator = (SCRIPTS / f"run_{name}_e2e.sh").read_text(encoding="utf-8")
        found = DEDICATED_RESULTS_RE.search(orchestrator)
        if found is None:
            raise ValueError(f"run_{name}_e2e.sh: no e2e_init with a P<n>_DIR")
        return f"p{found.group(1)}"
    return Path(config["resultsDir"]).name


def _notes(name: str, config: dict[str, str]) -> str:
    notes = []
    if config["runner"] == "dedicated":
        notes.append(f"Has its own orchestrator, `scripts/run_{name}_e2e.sh`.")
    if config.get("precondition", "none").startswith("env:"):
        variable = config["precondition"][len("env:") :]
        notes.append(
            f"Skipped, and Flame is not started, unless `{variable}` names an existing file."
        )
    if config.get("extraArgs") == "yes":
        notes.append("Takes extra client arguments from `E2E_EXTRA_ARGS`.")
    if config.get("crashCheck") == "yes":
        notes.append("Checks `shell.log` for an abnormal termination after the client returns.")
    return " ".join(notes) if notes else "-"


def render() -> str:
    lines = [PROSE_HEAD.rstrip("\n"), "", TABLE_HEAD.rstrip("\n")]
    for name in e2e_names():
        config = e2e_config(name)
        lines.append(
            f"| `{name}` | `{_results_folder(name, config)}` | "
            f"{_cell(client_checks(name))} | {_cell(_notes(name, config))} |"
        )
    return "\n".join(lines) + "\n"


def _check(expected: str) -> int:
    if not OUTPUT.exists():
        print(f"{OUTPUT} does not exist; run scripts/build_testing_doc.py", file=sys.stderr)
        return 1
    actual = OUTPUT.read_text(encoding="utf-8")
    if actual == expected:
        return 0
    diff = list(
        difflib.unified_diff(
            actual.splitlines(),
            expected.splitlines(),
            fromfile="docs/testing.md (on disk)",
            tofile="docs/testing.md (generated)",
            lineterm="",
        )
    )
    changed = sum(1 for line in diff if line[:1] in "+-" and line[:3] not in ("+++", "---"))
    print(f"docs/testing.md is out of date: {changed} changed line(s)", file=sys.stderr)
    print("\n".join(diff[:DIFF_PREVIEW_LINES]), file=sys.stderr)
    if len(diff) > DIFF_PREVIEW_LINES:
        print(f"... {len(diff) - DIFF_PREVIEW_LINES} more diff line(s)", file=sys.stderr)
    print("run: .venv/bin/python scripts/build_testing_doc.py", file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/testing.md is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        return _check(expected)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
