"""docs/testing.md is generated; it must match what the generator produces now."""

from __future__ import annotations

import importlib
import re
import sys
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS_DIR = ROOT / "scripts"
FORBIDDEN_REFERENCES = ("plan/", "research/", "refs/", "PLAN.md", "RULES.md")


def _generator() -> ModuleType:
    if str(SCRIPTS_DIR) not in sys.path:
        sys.path.insert(0, str(SCRIPTS_DIR))
    return importlib.import_module("build_testing_doc")


def test_testing_doc_is_up_to_date() -> None:
    generator = _generator()
    actual = (ROOT / "docs" / "testing.md").read_text(encoding="utf-8")
    assert actual == generator.render(), (
        "docs/testing.md is stale: run `.venv/bin/python scripts/build_testing_doc.py`"
    )


def test_doc_says_it_is_generated() -> None:
    doc = _generator().render()
    assert (
        "This file is generated by `scripts/build_testing_doc.py`. Do not edit it by hand." in doc
    )


def test_table_has_one_row_per_listed_e2e() -> None:
    generator = _generator()
    doc = generator.render()
    names = generator.e2e_names()
    rows = re.findall(r"^\| `([a-z0-9_]+)` \|", doc, flags=re.MULTILINE)
    assert rows == names
    assert len(names) == 29


def test_every_listed_e2e_has_a_checks_paragraph() -> None:
    generator = _generator()
    for name in generator.e2e_names():
        assert generator.client_checks(name).endswith("."), name


def test_doc_has_no_internal_references() -> None:
    doc = _generator().render()
    for reference in FORBIDDEN_REFERENCES:
        assert reference not in doc, reference


def test_doc_is_ascii() -> None:
    assert _generator().render().isascii()


def test_extract_checks_joins_a_wrapped_paragraph() -> None:
    source = '"""Title line.\n\nChecks: first part\nsecond part.\n\nMore text.\n"""\n'
    assert _generator().extract_checks(source, "x") == "first part second part."


def test_extract_checks_ignores_the_word_inside_other_text() -> None:
    source = '"""Title.\n\nThe list Checks: is not at the start of a line.\n"""\n'
    with pytest.raises(ValueError, match="x"):
        _generator().extract_checks(source, "x")


def test_extract_checks_rejects_a_missing_docstring() -> None:
    with pytest.raises(ValueError, match="x"):
        _generator().extract_checks("import os\n", "x")


def test_extract_checks_rejects_two_checks_paragraphs() -> None:
    source = '"""Title.\n\nChecks: a.\n\nChecks: b.\n"""\n'
    with pytest.raises(ValueError, match="x"):
        _generator().extract_checks(source, "x")


def test_doc_names_the_two_e2e_switches_and_the_dedicated_project_rule() -> None:
    doc = _generator().render()
    flat = " ".join(doc.split())

    assert "`FLAME_MCP_E2E_FLAME_VERSION`" in doc
    assert "`FLAME_MCP_E2E_PROJECT`" in doc
    assert "2025.2.4" in doc
    assert "`flame_mcp_probe`" in doc
    assert "project made in that version" in flat
    assert "converted" in flat
    assert "start with `flame_mcp_probe_`" in flat


def test_safety_doc_says_the_test_project_name_can_be_set() -> None:
    safety = (ROOT / "docs" / "safety.md").read_text(encoding="utf-8")

    assert "`FLAME_MCP_E2E_PROJECT`" in safety
    assert "`flame_mcp_probe_`" in safety
